// Copies contract ABIs from Foundry's build output (../out) into typed TS modules (lib/abi).
// Run `forge build` in the repo root first, then `pnpm abis`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "..", "out");
const abiDir = join(here, "..", "lib", "abi");
mkdirSync(abiDir, { recursive: true });

// [contract, source file] - the file defaults to the contract's name.
const contracts = [
  ["RiftMarket"],
  ["RiftReactive"],
  ["RiftPool"],
  ["MockVault"],
  ["MockToken"],
  ["RiftAgentVault"],
  ["RiftAgentVaultFactory", "RiftAgentVault"],
];
for (const [name, file = name] of contracts) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${file}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  const body = `// Generated by scripts/export-abis.mjs from out/${file}.sol/${name}.json. Do not edit.\nexport const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(abiDir, `${name}.ts`), body);
  console.log(`wrote lib/abi/${name}.ts (${artifact.abi.length} entries)`);
}
